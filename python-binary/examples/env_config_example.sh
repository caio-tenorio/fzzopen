# Example configuration using environment variables
# Add to your ~/.bashrc, ~/.zshrc, or config.fish

# Preferred editor for text files
export FZZOPEN_TEXT_EDITOR="nvim"

# Preferred file manager
export FZZOPEN_FILE_MANAGER="nautilus"

# Preferred image viewer
export FZZOPEN_IMAGE_VIEWER="loupe"

# Preferred PDF viewer
export FZZOPEN_PDF_VIEWER="okular"

# Directories to exclude (colon-separated)
export FZZOPEN_EXCLUDE_DIRS=".git:node_modules:.vscode:.idea:dist:build:target:.cache"

# Use fd if available (true/false)
export FZZOPEN_USE_FD="true"

# fzf height
export FZZOPEN_FZF_HEIGHT="90%"

# Show hidden files by default (true/false)
export FZZOPEN_SHOW_HIDDEN="false"
